# Punctuation/emoji variations
EMPHASIS_PATTERNS = ["!", "!!", "!!!", "", "?", "???", " 🚀", " 📈", " 🔥", ""]


class SyntheticSocialProvider:
    """Offline social provider generating deterministic test data.

    Generates compositional posts with realistic sentiment distribution and
    author pooling. Seeds the PRNG for reproducibility. Text is never templated;
    instead, sentences are composed from randomised openers, claims, reasoning,
    and optional catalysts/position disclosures, all drawing from the actual
    sentiment-bearing vocabulary of the rule classifier.
    """

    name: str = "synthetic"

    def __init__(
        self,
        source: SocialSource = SocialSource.REDDIT,
        seed: int = 42,
        signal_strength: float = 0.15,
        base_author_salt: str = "synthetic",
    ):
        """Initialize the synthetic provider.

        Args:
            source: SocialSource.REDDIT or SocialSource.X.
            seed: PRNG seed for reproducibility.
            signal_strength: Correlation strength between sentiment and price (0-1).
            base_author_salt: Salt for pseudonymising author names.
        """
        self.source = source
        self.seed = seed
        self.signal_strength = signal_strength
        self.base_author_salt = base_author_salt
        self._rng = random.Random(seed)
        self._author_pools: dict[str, list[str]] = {}
        self._spam_symbols: set[str] = set()

    def status(self) -> ProviderStatus:
        """Report provider status."""
        return ProviderStatus(
            name=self.name,
            kind="social",
            available=True,
            configured=True,
            message=f"Synthetic {self.source} provider (seed={self.seed})",
            supports_point_in_time=True,
            rate_limit_per_minute=None,
            licence_note="Offline test data; not real social media",
            capabilities={"fetch": True, "search": True},
        )

    def _get_author_pool(self, symbol: str) -> list[str]:
        """Get or create bounded author pool for symbol (30-120 authors).

        Authors are created once per symbol and reused with power-law
        distribution (some authors post many times, most post few).
        """
        if symbol not in self._author_pools:
            # Create bounded pool (30-120 authors) deterministically for this symbol
            rng = random.Random(f"{self.seed}:{symbol}")
            num_authors = rng.randint(30, 120)
            self._author_pools[symbol] = [
                pseudonymise(f"{symbol}_{i}", salt=self.base_author_salt)
                for i in range(num_authors)
            ]
        return self._author_pools[symbol]

    def _choose_author(self, symbol: str, post_index: int) -> str:
        """Choose an author from the pool using power-law distribution.

        The PRNG state is deterministic given seed and post_index, so the
        same post will always get the same author.
        """
        pool = self._get_author_pool(symbol)
        # Power-law: bias heavily toward first authors. Exponent of 1.5 gives
        # a realistic heavy-tailed distribution.
        rng = random.Random(f"{self.seed}:{symbol}:{post_index}")
        # Zipfian: pick index proportional to 1/rank^1.5
        idx_float = rng.random() ** (1.0 / 1.5)
        idx = int(idx_float * len(pool)) % len(pool)
        return pool[idx]

    def _compose_bullish_post(self, symbol: str) -> str:
        """Generate a bullish post using strong lexicon-bearing vocabulary.

        Structure: opener + multiple bullish claims + reasoning + position.
        Include multiple sentiment-bearing terms for strong classifier signal.
        """
        opener = self._rng.choice(OPENERS)
        bullish_words = list(BULLISH_TERMS.keys())

        # Use multiple bullish terms for strong signal
        claim1 = self._rng.choice(bullish_words[:12])
        claim2 = self._rng.choice(bullish_words[:12]) if self._rng.random() < 0.5 else None

        # Build text ensuring no periods directly after lexicon phrases
        # (periods break word boundary matching in the classifier)
        text_parts = [f"{opener} {symbol}"]

        # Add main bullish claims - construct sentences carefully
        text_parts.append(f"The {claim1} thesis is compelling")

        if claim2 and claim2 != claim1:
            text_parts.append(f"and {claim2} signals are strong")

        # Add reasoning with more vocabulary
        if self._rng.random() < 0.6:
            reasoning_options = [
                "Fundamentals are strong and price action supports it",
                "The technical setup confirms this thesis",
                "Multiple catalysts could drive it higher",
                "Accumulation pattern looks bullish",
            ]
            text_parts.append(self._rng.choice(reasoning_options))

        # Add position disclosure
        if self._rng.random() < 0.5:
            pos_phrase = self._rng.choice(list(POSITION_DISCLOSURE_PATTERNS.keys())[:8])
            text_parts.append(f"{pos_phrase} {symbol}")

        text = ". ".join(text_parts) + "."

        # Add emphasis
        if self._rng.random() < 0.3:
            text += " " + self._rng.choice(["🚀", "📈", "!", "!!"])

        return text

    def _compose_bearish_post(self, symbol: str) -> str:
        """Generate a bearish post using strong lexicon-bearing vocabulary.

        Structure: opener + multiple bearish claims + reasoning + position.
        Include multiple sentiment-bearing terms for strong classifier signal.
        """
        opener = self._rng.choice(OPENERS)
        bearish_words = list(BEARISH_TERMS.keys())
        fear_words = list(FEAR_TERMS.keys())

        # Use multiple bearish terms for strong signal
        claim1 = self._rng.choice(bearish_words[:12])
        claim2 = self._rng.choice(bearish_words[:12]) if self._rng.random() < 0.5 else None
        fear = self._rng.choice(fear_words[:8]) if self._rng.random() < 0.5 else None

        # Build text carefully - avoid periods directly after lexicon phrases
        text_parts = [f"{opener} {symbol}"]

        # Add main bearish claims
        text_parts.append(f"The {claim1} thesis is concerning")

        if claim2 and claim2 != claim1:
            text_parts.append(f"and {claim2} signals are troubling")

        if fear:
            text_parts.append(f"with {fear} risks evident")

        # Add reasoning
        if self._rng.random() < 0.6:
            reasoning_options = [
                "Fundamentals are deteriorating",
                "Multiple red flags emerging",
                "Price action is weakening",
                "Valuation looks stretched",
            ]
            text_parts.append(self._rng.choice(reasoning_options))

        # Add position disclosure
        if self._rng.random() < 0.4:
            pos_phrase = self._rng.choice(list(POSITION_DISCLOSURE_PATTERNS.keys())[-8:])
            text_parts.append(f"{pos_phrase} {symbol}")

        text = ". ".join(text_parts) + "."

        # Add emphasis
        if self._rng.random() < 0.2:
            text += " " + self._rng.choice(["📉", "⚠️", "!", "??"])

        return text

    def _compose_neutral_post(self, symbol: str) -> str:
        """Generate a neutral/discussion post with uncertainty signals.

        These posts avoid strong directional signals, focusing on discussion
        and uncertainty instead.
        """
        opener = self._rng.choice(OPENERS)

        uncertainty_words = list(UNCERTAINTY_HEDGE_TERMS.keys())
        uncertain = self._rng.choice(uncertainty_words[:8])

        discussion_options = [
            f"What's everyone's take on {symbol}?",
            f"Anyone else tracking {symbol} right now?",
            f"Interesting developments with {symbol} this quarter.",
            f"The {symbol} story is complex right now.",
            f"Hard to say which way {symbol} breaks.",
            f"Waiting for more clarity on {symbol}.",
        ]
        discussion = self._rng.choice(discussion_options)

        text_parts = [f"{opener} {symbol}."]
        text_parts.append(uncertain)
        text_parts.append(discussion)

        text = " ".join(text_parts)
        return text

    def _compose_mixed_post(self, symbol: str) -> str:
        """Generate a mixed/conflicted post with both bullish and bearish signals.

        These have real bullish and bearish sentiment that partially cancel out.
        """
        opener = self._rng.choice(OPENERS)

        bullish_words = list(BULLISH_TERMS.keys())
        bearish_words = list(BEARISH_TERMS.keys())

        bullish = self._rng.choice(bullish_words[:10])
        bearish = self._rng.choice(bearish_words[:10])

        # Build text carefully - avoid periods directly after lexicon phrases
        text_parts = [f"{opener} {symbol}"]
        text_parts.append(f"The {bullish} thesis has merit")

        connectors = [
            "but the risks are real",
            "though concerns remain",
            "yet headwinds exist",
            "however {bearish} signals emerged",
            "despite {bearish} indicators",
        ]
        connector = self._rng.choice(connectors).format(bearish=bearish)
        text_parts.append(connector)

        # Add some reasoning to both sides
        if self._rng.random() < 0.4:
            text_parts.append("On balance it is unclear")

        text = ". ".join(text_parts) + "."
        return text

    def _compose_spam_post(self, symbol: str) -> str:
        """Generate a spam/pump post using PUMP_DUMP vocabulary."""
        pump_phrases = list(PUMP_DUMP_TEMPLATES.keys())
        main_phrase = self._rng.choice(pump_phrases[:8])

        text_options = [
            f"{symbol} {main_phrase}!!!",
            f"BUY {symbol} {main_phrase} NOW",
            f"{symbol} - {main_phrase} - Don't miss out",
            f"This is the play! {symbol} {main_phrase}",
        ]
        text = self._rng.choice(text_options)
        return text

    def _compose_post(self, symbol: str, sentiment_type: str) -> str:
        """Compose a post of the given sentiment type using vocabulary mixing."""
        if sentiment_type == "bullish":
            return self._compose_bullish_post(symbol)
        elif sentiment_type == "bearish":
            return self._compose_bearish_post(symbol)
        elif sentiment_type == "neutral":
            return self._compose_neutral_post(symbol)
        elif sentiment_type == "mixed":
            return self._compose_mixed_post(symbol)
        elif sentiment_type == "spam":
            return self._compose_spam_post(symbol)
        else:
            return self._compose_neutral_post(symbol)

    def _choose_sentiment_type(self, symbol: str) -> str:
        """Choose sentiment type with per-symbol realistic distribution.

        Returns one of: "bullish", "bearish", "neutral", "mixed", with
        per-symbol bias so different symbols have genuinely different
        aggregate polarity. Some symbols lean bullish (50%+), others bearish
        (40%+). The global average is ~35/25/25/15 but individual symbols
        vary significantly.
        """
        # Create per-symbol bias deterministically from symbol name hash
        # using SHA256 for determinism across Python restarts.
        symbol_digest = hashlib.sha256(symbol.encode()).hexdigest()
        symbol_hash = int(symbol_digest, 16) % 100 / 100.0  # ranges [0, 1)

        # Map symbol_hash to a bias range. Create multiple "bands":
        # - 0.00-0.25: strongly bearish (3 symbols expected with ~12 symbols)
        # - 0.25-0.45: mildly bearish
        # - 0.45-0.55: neutral (balanced)
        # - 0.55-0.75: mildly bullish
        # - 0.75-1.00: strongly bullish (3 symbols expected)
        if symbol_hash < 0.25:
            symbol_bias = -0.8  # strongly bearish
        elif symbol_hash < 0.45:
            symbol_bias = -0.3  # mildly bearish
        elif symbol_hash < 0.55:
            symbol_bias = 0.0   # neutral
        elif symbol_hash < 0.75:
            symbol_bias = 0.3   # mildly bullish
        else:
            symbol_bias = 0.8   # strongly bullish

        # Apply symbol bias to base distribution: 35% bullish, 25% bearish
        # Use strong shift (0.35) to ensure clear polarity separation between symbols
        bias_shift = symbol_bias * 0.35

        bullish_pct = 0.35 + bias_shift
        bearish_pct = 0.25 - bias_shift
        neutral_pct = 0.25
        mixed_pct = 0.15

        # Clamp to valid ranges to ensure both bullish and bearish exist
        bullish_pct = max(0.05, min(0.70, bullish_pct))
        bearish_pct = max(0.05, min(0.60, bearish_pct))
        # Renormalize
        total = bullish_pct + bearish_pct + neutral_pct + mixed_pct
        bullish_pct /= total
        bearish_pct /= total
        neutral_pct /= total
        mixed_pct /= total

        roll = self._rng.random()
        if roll < bullish_pct:
            return "bullish"
        elif roll < bullish_pct + bearish_pct:
            return "bearish"
        elif roll < bullish_pct + bearish_pct + neutral_pct:
            return "neutral"
        else:
            return "mixed"

    def fetch_posts(
        self,
        *,
        since: dt.datetime,
        until: dt.datetime | None = None,
        symbols: list[str] | None = None,
        limit: int | None = None,
    ) -> list[SocialPost]:
        """Generate synthetic posts for the given time window.

        Args:
            since: Start of time window (tz-aware UTC).
            until: End of time window; defaults to now.
            symbols: Hint for which symbols to mention (all are included).
            limit: Maximum posts to return.

        Returns:
            List of SocialPost, newest first, all with tz-aware UTC created_at.
        """
        if until is None:
            until = dt.datetime.now(tz=dt.UTC)

        if symbols is None:
            symbols = ["NVDA", "TSLA", "APPL", "MSFT", "META", "AMZN"]

        # Determine which symbols get spam treatment (near-duplicate clustering)
        # A handful of symbols (~20%) get high duplicate_ratio, rest get low
        rng_spam = random.Random(f"{self.seed}:spam_symbols")
        num_spam = max(1, len(symbols) // 5)
        self._spam_symbols = set(rng_spam.sample(symbols, k=num_spam))

        # Generate ~30 posts per day in the window
        window_days = max(1, (until - since).days)
        target_count = window_days * 30
        if limit is not None:
            target_count = min(target_count, limit)

        posts: list[SocialPost] = []
        recent_spam_hashes: dict[str, list[str]] = {}

        for i in range(target_count):
            # Distribute posts evenly across the window
            t = since + (until - since) * (i / max(1, target_count - 1))
            created_at = t.replace(tzinfo=dt.UTC)

            # Pick a symbol
            symbol = self._rng.choice(symbols)

            # Decide post type: most are composed, some are hard negatives,
            # few are injections, some are spam.
            post_type_roll = self._rng.random()
            if post_type_roll < 0.05:
                post_type = "ambiguous_ticker"
            elif post_type_roll < 0.07:
                post_type = "injection"
            elif symbol in self._spam_symbols and self._rng.random() < 0.15:
                post_type = "spam"
            else:
                post_type = "composed"

            if post_type == "ambiguous_ticker":
                text = self._rng.choice(HARD_NEGATIVE_TEMPLATES)
            elif post_type == "injection":
                text = f"{self._rng.choice(INJECTION_STRINGS)} This is about {symbol}."
            elif post_type == "spam":
                text = self._compose_spam_post(symbol)
                # For spam symbols, duplicate some hashes (near-duplicate cluster)
                if symbol not in recent_spam_hashes:
                    recent_spam_hashes[symbol] = []
            else:
                # Composed post with realistic sentiment distribution
                sentiment_type = self._choose_sentiment_type(symbol)
                text = self._compose_post(symbol, sentiment_type)

            sanitised = sanitize_social_text(text)

            # Engagement: roughly proportional to post type and sentiment
            score = self._rng.randint(0, 200 if post_type == "spam" else 50)
            num_comments = self._rng.randint(0, 30)
            num_replies = self._rng.randint(0, 20)

            # Author: use bounded pool per symbol
            author_hash = self._choose_author(symbol, i)

            # Some bot-like accounts (very new, high posting rate)
            is_bot = self._rng.random() < 0.08
            author_age_days = self._rng.random() * (10 if is_bot else 1000)

            # Text hash for dedup: spam symbols get near-duplicate clusters
            if post_type == "spam" and symbol in recent_spam_hashes:
                if self._rng.random() < 0.4 and recent_spam_hashes[symbol]:
                    # Reuse a recent spam hash (near-duplicate)
                    text_hash_val = self._rng.choice(recent_spam_hashes[symbol])
                else:
                    text_hash_val = text_hash(sanitised)
                    recent_spam_hashes[symbol].append(text_hash_val)
                    # Keep pool small to maintain clustering
                    if len(recent_spam_hashes[symbol]) > 5:
                        recent_spam_hashes[symbol].pop(0)
            else:
                text_hash_val = text_hash(sanitised)

            injection_risk = injection_risk_score(text)

            post = SocialPost(
                source=self.source,
                external_id=f"synthetic-{self.seed}-{i}",
                created_at=created_at,
                text=sanitised,
                community="r/stocks" if self.source == SocialSource.REDDIT else "finance",
                score=score,
                num_comments=num_comments,
                num_reposts=0,
                num_replies=num_replies,
                author_hash=author_hash,
                author_age_days=author_age_days,
                author_karma=(
                    self._rng.random() * 1000
                    if not is_bot
                    else self._rng.random() * 10
                ),
                author_followers=None,
                is_comment=self._rng.random() < 0.3,
                parent_id=None,
                is_removed=False,
                is_crosspost=False,
                crosspost_parent=None,
                text_hash=text_hash_val,
                duplicate_group=None,
                injection_risk=injection_risk,
                fetched_at=dt.datetime.now(tz=dt.UTC),
            )
            posts.append(post)

        # Sort newest first
        posts.sort(key=lambda p: p.created_at, reverse=True)
        return posts


class SyntheticRedditProvider(SyntheticSocialProvider):
    """Synthetic Reddit provider."""

